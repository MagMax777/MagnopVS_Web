/**
 * Astronomical Sun Position calculation for Day/Night Terminator
 * Computes subsolar point latitude and longitude for a given UTC timestamp.
 */
export function calculateSubsolarPoint(date: Date = new Date()): { lat: number; lng: number } {
  // Day of the year
  const startOfYear = new Date(Date.UTC(date.getUTCFullYear(), 0, 1));
  const dayOfYear = Math.floor((date.getTime() - startOfYear.getTime()) / 86400000);

  // Approximate Solar Declination (latitude where sun is directly overhead)
  // Max ~23.44° on summer solstice, -23.44° on winter solstice
  const declination = -23.44 * Math.cos(((2 * Math.PI) / 365.25) * (dayOfYear + 10));

  // Subsolar Longitude: Earth rotates 360° in 24 hours (15° per hour)
  // At 12:00 UTC, sun is roughly at 0° longitude.
  const utcHours = date.getUTCHours() + date.getUTCMinutes() / 60 + date.getUTCSeconds() / 3600;
  const subsolarLng = -(utcHours - 12) * 15;

  return {
    lat: declination,
    lng: ((subsolarLng + 180) % 360) - 180, // Normalize to [-180, 180]
  };
}

/**
 * Checks if a geographic coordinate [lat, lng] is in daylight or night
 * based on solar angular distance from subsolar point.
 */
export function isDaylightAtLocation(lat: number, lng: number, subsolarPoint: { lat: number; lng: number }): boolean {
  const phi1 = (lat * Math.PI) / 180;
  const phi2 = (subsolarPoint.lat * Math.PI) / 180;
  const deltaLambda = ((lng - subsolarPoint.lng) * Math.PI) / 180;

  // Great-circle angular distance
  const cosDistance = Math.sin(phi1) * Math.sin(phi2) + Math.cos(phi1) * Math.cos(phi2) * Math.cos(deltaLambda);

  // Distance > 90° means below horizon (night)
  // cosDistance > 0 means sun above horizon (day)
  return cosDistance > -0.05; // -0.05 accounts for civil twilight
}
